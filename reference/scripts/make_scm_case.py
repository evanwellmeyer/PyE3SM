#!/usr/bin/env python3
"""Create a run directory for the single-column EAMxx reference driver (scm_eamxx).

  python reference/scripts/make_scm_case.py CASE [--lr] [--hours H] [--out DIR] [--every N]

The physics settings are those of reference/scripts/make_dp_case.py (CIME's DP-EAMxx
defaults, or the EAMxx-LR ZM configuration with --lr). The process list is
  eamxx: [sc_import, scm_host, (scm_sfc_flux when the case has no IOP surface fluxes), physics]
with physics = [iop_forcing, (zm,) mac_aero_mic, rrtmgp].

The initial state is the port's single-column initial state (eamxx_torch.scm.SCM:
DP-EAMxx's constants, the IC and topography files at the column EAMxx would pick, the
IOP file, the initial-run settings), written into a one-column IC file. EAMxx's own
initialization from the IOP file (IOPDataManager::set_fields_from_iop_data) works on
the dycore's GLL grid only, so the reference starts from the same state rather than
building it; the comparison checks the time stepping. SHOC's cell length is the
planar DP grid's (dx_short: 3.333... km for the 50 km DP domains, 111 km for LR).

Outputs every step, or every N steps with --every (instant, double precision): see OUTPUT_FIELDS.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import make_dp_case as dp  # noqa: E402

REF = HERE.parent
DATA = REF / "inputdata" / "atm"
DX_SHORT = {False: 3.333333333333333, True: 111.0}   # km; SHOC cell length = dx_short*1000
OUTPUT_FIELDS = [
    "T_mid", "qv", "qc", "qi", "qr", "qm", "nc", "nr", "ni", "bm", "horiz_winds", "tke",
    "cldfrac_liq", "cldfrac_tot", "cldfrac_ice", "sgs_buoy_flux", "eddy_diff_mom",
    "eddy_diff_heat", "inv_qc_relvar", "pbl_height", "thl_sec", "w_variance",
    "precip_liq_surf_mass", "precip_ice_surf_mass", "surf_sens_flux", "surf_evap",
    "surf_mom_flux", "surf_lw_flux_up", "surf_radiative_T", "p_mid", "pseudo_density_dry",
    "omega", "rad_heating_pdel", "SW_flux_dn", "SW_flux_up", "LW_flux_dn", "LW_flux_up",
    "eff_radius_qc", "eff_radius_qi", "nccn", "T_prev_micro_step", "qv_prev_micro_step",
    "cldtot",
]
ZM_OUTPUT = ["zm_prec", "zm_cape", "zm_dcape", "zm_activity", "zm_t_prev", "zm_q_prev"]


def physics_block(lr: bool) -> str:
    """The physics sublist of make_dp_case's input.yaml (same settings)."""
    txt = dp.INPUT_YAML
    i = txt.index("  physics:\n")
    j = txt.index("\ngrids_manager:")
    blk = txt[i:j + 1]
    tables = ", ".join(
        str(DATA / "scream/tables" / t)
        for t in ("p3_lookup_table_1.dat-v4.1.1", "mu_r_table_vals_v2.dat8",
                  "revap_table_vals_v2.dat8", "vn_table_vals_v2.dat8", "vm_table_vals_v2.dat8"))
    return blk.format(
        physics_list="iop_forcing,zm,mac_aero_mic,rrtmgp" if lr else "iop_forcing,mac_aero_mic,rrtmgp",
        zm_block=dp.ZM_BLOCK if lr else "", mac_subcycles=12 if lr else 1,
        rad_frequency=2 if lr else 3,
        spa_file=DATA / "scream/init/spa_file_unified_and_complete_ne4_20220428.nc",
        p3_tables=tables, data=DATA)


